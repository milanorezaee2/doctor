const digits = (v: string) => v.replace(/[^\d+]/g, '');

export const telHref = `tel:${digits(site.contact.telE164)}`;
export const mailHref = (subject: string, body: string) =>
  `mailto:${site.contact.email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
export const mapHref = `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(site.contact.mapQuery)}`;
